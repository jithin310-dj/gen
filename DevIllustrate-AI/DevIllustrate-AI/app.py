import os
from datetime import datetime
from io import BytesIO

import streamlit as st

from config import (
    APP_TITLE, APP_DESCRIPTION, MODEL_ID,
    DEFAULT_STEPS, DEFAULT_GUIDANCE, OUTPUT_DIR
)
from generator import create_pipeline, generate_image
from prompt_engine import enhance_prompt, get_negative_prompt

st.set_page_config(page_title=APP_TITLE, page_icon="🎨", layout="wide")

st.markdown("""
<style>
.main-title { text-align:center; font-size:38px; font-weight:700; color:#2563eb; }
.subtitle { text-align:center; color:gray; font-size:16px; }
</style>
""", unsafe_allow_html=True)

st.markdown(f'<div class="main-title">{APP_TITLE}</div>', unsafe_allow_html=True)
st.markdown(f'<div class="subtitle">{APP_DESCRIPTION}</div>', unsafe_allow_html=True)
st.divider()

@st.cache_resource(show_spinner="Loading Stable Diffusion model... This may take several minutes the first time.")
def load_model():
    return create_pipeline(MODEL_ID)

with st.sidebar:
    st.header("⚙️ Generation settings")
    style = st.selectbox(
        "Illustration style",
        ["Professional 3D", "Flat Vector", "Blueprint", "Isometric"]
    )
    steps = st.slider("Inference steps", 10, 50, DEFAULT_STEPS)
    guidance = st.slider("Guidance scale", 1.0, 15.0, DEFAULT_GUIDANCE, 0.5)
    resolution = st.selectbox("Image resolution", ["512x512", "512x768", "768x512"])
    seed = st.number_input("Random seed", min_value=0, max_value=999999, value=42, step=1)

st.subheader("📝 Describe your technical illustration")
prompt = st.text_area(
    "Image description",
    placeholder="Example: A cloud computing architecture showing users, frontend, backend, database and cloud servers.",
    height=130
)

with st.expander("Advanced prompt settings"):
    negative_prompt = st.text_area("Negative prompt", value=get_negative_prompt(), height=100)

if st.button("🚀 Generate technical illustration", type="primary", use_container_width=True):
    if not prompt.strip():
        st.warning("Please enter an image description.")
    else:
        width, height = map(int, resolution.split("x"))
        final_prompt = enhance_prompt(prompt.strip(), style)

        st.subheader("Enhanced prompt")
        st.write(final_prompt)

        try:
            with st.spinner("Generating your illustration. The first run also downloads the model..."):
                pipe = load_model()
                image = generate_image(
                    pipe=pipe,
                    prompt=final_prompt,
                    negative_prompt=negative_prompt,
                    steps=steps,
                    guidance=guidance,
                    width=width,
                    height=height,
                    seed=int(seed)
                )

            st.success("Image generated successfully!")
            st.image(image, caption="Generated by DevIllustrate AI", use_container_width=True)

            os.makedirs(OUTPUT_DIR, exist_ok=True)
            filename = "DevIllustrate_" + datetime.now().strftime("%Y%m%d_%H%M%S") + ".png"
            image_path = os.path.join(OUTPUT_DIR, filename)
            image.save(image_path)

            buffer = BytesIO()
            image.save(buffer, format="PNG")
            st.download_button(
                "⬇️ Download PNG",
                data=buffer.getvalue(),
                file_name=filename,
                mime="image/png",
                use_container_width=True
            )
            st.caption(f"Saved locally to: {image_path}")

        except Exception as exc:
            st.error(f"Image generation failed: {exc}")
            st.info(
                "Check your internet connection, model access and available memory. "
                "For faster generation, use a supported NVIDIA GPU. "
                "If the model repository requires access approval, accept its terms on Hugging Face."
            )

st.divider()
st.caption("DevIllustrate AI | Technical Documentation Graphic Generator")
